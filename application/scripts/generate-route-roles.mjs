// Generate app/utils/route-roles.generated.ts from the server route handlers.
//
// Each route declares its required roles once, as `const REQUIRED_ROLES` used by
// `requireAuth`. Nitro's OpenAPI extractor can't fold those into the spec, so we
// mirror them into a small committed map keyed by `{method} {path}` that the
// in-app API reference reads to show who can call each endpoint.
//
// Run `npm run app:gen:route-roles` after changing a route's REQUIRED_ROLES; the
// route-roles unit test fails if this file drifts from the sources.
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildRouteRoles } from './route-roles-extract.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const appDir = resolve(__dirname, '..');
const serverDir = resolve(appDir, 'server');
const outFile = resolve(appDir, 'app/utils/route-roles.generated.ts');

const map = buildRouteRoles(serverDir);

const entries = Object.entries(map)
  .map(([key, roles]) => `  ${JSON.stringify(key)}: [${roles.map((r) => JSON.stringify(r)).join(', ')}],`)
  .join('\n');

const contents = `// AUTO-GENERATED by scripts/generate-route-roles.mjs — do not edit by hand.
// Regenerate with \`npm run app:gen:route-roles\` after changing a route's
// REQUIRED_ROLES. The route-roles unit test guards against drift.
//
// Maps an OpenAPI operation ("{method} {path}") to the roles that may call it
// (the route's runtime REQUIRED_ROLES). Routes with no role restriction — public
// or token-authenticated — are intentionally absent.
export const ROUTE_ROLES: Record<string, string[]> = {
${entries}
};
`;

writeFileSync(outFile, contents);
console.log(`Wrote ${Object.keys(map).length} route-role entries to ${outFile.replace(appDir + '/', '')}`);
